// TestSeededDeliveriesParse is the integration contract between the two halves of
// the challenge that were built independently: internal/seed writes the legacy
// deliveries, this package parses them. If the generator and the parser ever
// disagree about the format, every pipeline scenario breaks at once, so this test
// runs the real generated bytes of every scenario through the real importer.
func TestSeededDeliveriesParse(t *testing.T) {
	f := kredexp.New()
	for _, scenario := range []string{"S0", "S1", "S2"} {
		t.Run(scenario, func(t *testing.T) {
			ds, err := seed.Generate(scenario, 20260831)
			if err != nil {
				t.Fatalf("seed.Generate: %v", err)
			}
			if len(ds.Deliveries) == 0 {
				t.Fatal("scenario generated no legacy delivery")
			}
			for _, d := range ds.Deliveries {
				if !f.Detect(d.Bytes, importer.Options{Filename: d.Name}) {
					t.Errorf("%s: Detect said no", d.Name)
				}
				res, err := f.Parse(context.Background(), d.Bytes, importer.Options{Filename: d.Name})
				if err != nil {
					t.Fatalf("%s: Parse returned an error, which is reserved for programming faults: %v", d.Name, err)
				}
				// A generated delivery is always a VALID file: the invalid
				// variants live only in the Go task's fixtures. So it must be
				// accepted, with no fatal and no reject diagnostic, and its
				// trailer must verify.
				var fatal, reject []string
				warn := map[string]int{}
				for _, dg := range res.Diagnostics {
					switch dg.Severity {
					case importer.SeverityFatal:
						fatal = append(fatal, string(dg.Code)+" line "+itoa(dg.Line)+" "+dg.Message)
					case importer.SeverityReject:
						reject = append(reject, string(dg.Code)+" line "+itoa(dg.Line)+" field "+dg.Field)
					default:
						warn[string(dg.Code)]++
					}
				}
				if len(fatal) > 0 {
					t.Fatalf("%s: fatal diagnostics on a valid delivery:\n  %s", d.Name, strings.Join(fatal, "\n  "))
				}
				if len(reject) > 0 {
					t.Fatalf("%s: %d record rejects on a valid delivery:\n  %s", d.Name, len(reject), strings.Join(reject, "\n  "))
				}
				if !res.Accepted {
					t.Fatalf("%s: not accepted although there is no fatal and no reject", d.Name)
				}
				if got, want := len(res.Documents), d.KopfCount; want > 0 && got != want {
					t.Errorf("%s: parsed %d documents, the generator wrote %d", d.Name, got, want)
				}
				// The two ambiguity markers are the point of the whole task, so
				// the generated data must actually trigger them somewhere.
				t.Logf("%s: %d documents, warnings %v", d.Name, len(res.Documents), warn)
			}
		})
	}
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var b [20]byte
	i := len(b)
	neg := n < 0
	if neg {
		n = -n
	}
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	if neg {
		i--
		b[i] = '-'
	}
	return string(b[i:])
}
